"""Command line entry point for the Bridge-Agents server.

Usage::

    bridge-agents init            # write bridge-agents.toml + .env, print next steps
    bridge-agents config check    # validate configuration and show warnings
    bridge-agents serve           # serve the API (and the built UI when present)
    bridge-agents init-db         # create the database schema
    bridge-agents demo            # one command: mock model + API + built web UI
    bridge-agents doctor          # check the local demo prerequisites
    bridge-agents version         # print package versions

The ``demo`` command is intentionally dependency-free: it starts the bundled
deterministic mock model, enables the demo login, and serves the built React UI
on the same port, so a fresh checkout only needs ``uv sync`` and Node for the
first web build. ``init``/``serve`` are the deployment path.
"""

from __future__ import annotations

import argparse
import os
import secrets
import shutil
import socket
import subprocess
import sys
import time
import urllib.request
from importlib.metadata import PackageNotFoundError
from importlib.metadata import version as distribution_version
from pathlib import Path

DEFAULT_HOST = "0.0.0.0"
DEFAULT_PORT = 8000
DEFAULT_MOCK_PORT = 8001
DEFAULT_CONFIG_FILE = "bridge-agents.toml"
DEFAULT_ENV_FILE = ".env"

TOML_TEMPLATE = """\
# Bridge-Agents server configuration (non-secret values only).
# Precedence: CLI arguments > environment variables > .env > this file.
app_name = "Bridge-Agents"
app_env = "{app_env}"
debug = false
log_level = "INFO"

# HTTP server
host = "0.0.0.0"
port = 8000
allowed_hosts = "{allowed_hosts}"
cors_origins = ""

# Storage
database_url = "sqlite+aiosqlite:///./data/bridge-agents.db"
storage_dir = "./data/uploads"
docs_dir = "./docs/kb"
knowledge_dir = "./data/knowledge"
web_dist_dir = "web/dist"

# Authentication
# hs256 = local tokens; rs256_pem / jwks = external identity provider.
auth_verifier = "hs256"
allow_dev_login = {allow_dev_login}
jwt_issuer = "bridge-agents"

# Model provider (the API key stays in .env)
llm_provider = "openai"
openai_base_url = "https://api.openai.com/v1"
openai_model = "gpt-4o-mini"
openai_timeout = 60
openai_max_retries = 3
"""

ENV_TEMPLATE = """\
# Secrets generated by `bridge-agents init`. Never commit this file.
JWT_SECRET={jwt_secret}
# Model provider key used by the configured LLM provider.
OPENAI_API_KEY=
# Optional provider moderation key.
MODERATION_API_KEY=
"""


def _repo_root() -> Path | None:
    """Return the checkout root when the CLI runs from a source tree."""
    candidates = [Path(__file__).resolve().parents[1], Path.cwd(), *Path.cwd().parents]
    for candidate in candidates:
        if (candidate / "pyproject.toml").is_file() and (candidate / "app" / "main.py").is_file():
            return candidate
    return None


def _load_settings(config_path: str | None):
    """Build Settings, pointing BRIDGE_CONFIG at the requested TOML file."""
    if config_path:
        os.environ["BRIDGE_CONFIG"] = str(Path(config_path).expanduser().resolve())
    from bridge_agents.config import Settings

    return Settings()


def _settings_issues(settings) -> list[tuple[str, str]]:
    """Return ``(level, message)`` pairs for configuration problems."""
    issues: list[tuple[str, str]] = []
    production = settings.is_production
    secret = settings.jwt_secret or ""

    if production and settings.allow_dev_login:
        issues.append(("error", "allow_dev_login must be false in production"))
    if settings.auth_verifier == "hs256":
        if secret == "dev-only-change-me" or len(secret) < 32:
            issues.append(
                (
                    "error" if production else "warning",
                    "JWT_SECRET should be a random string of at least 32 characters",
                )
            )
    elif settings.auth_verifier == "rs256_pem":
        if not settings.rs256_public_key_path:
            issues.append(("error", "RS256_PUBLIC_KEY_PATH is required for rs256_pem"))
    elif settings.auth_verifier == "jwks":
        if not settings.jwks_url:
            issues.append(("error", "JWKS_URL is required for the jwks verifier"))
    else:
        issues.append(("error", f"unknown auth_verifier: {settings.auth_verifier!r}"))

    if production and "*" in settings.allowed_host_list:
        issues.append(("warning", "ALLOWED_HOSTS='*' is not recommended in production"))
    if settings.web_dist_dir and not (Path(settings.web_dist_dir) / "index.html").is_file():
        issues.append(
            (
                "warning",
                f"no built web UI at {settings.web_dist_dir!r}; the API will run without the GUI",
            )
        )
    if production and settings.openai_api_key in ("", "not-needed"):
        issues.append(("warning", "OPENAI_API_KEY is empty for a production deployment"))
    return issues


def _lan_address() -> str:
    """Best-effort local network address for the printed demo URL."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
            probe.connect(("8.8.8.8", 80))
            return str(probe.getsockname()[0])
    except OSError:
        try:
            return socket.gethostbyname(socket.gethostname())
        except OSError:
            return "127.0.0.1"


def _demo_environment(root: Path, mock_port: int) -> dict[str, str]:
    """Environment overrides that make a checkout run like the Docker demo."""
    return {
        "APP_ENV": "development",
        "ALLOW_DEV_LOGIN": "true",
        "ALLOWED_HOSTS": "*",
        "LLM_MODE": "mock",
        "OPENAI_BASE_URL": f"http://127.0.0.1:{mock_port}/v1",
        "WEB_DIST_DIR": str(root / "web" / "dist"),
    }


def _ensure_env_file(root: Path) -> Path | None:
    """Copy ``.env.example`` to ``.env`` on first run (never overwrite)."""
    env_file = root / ".env"
    if env_file.exists():
        return env_file
    example = root / ".env.example"
    if not example.is_file():
        return None
    shutil.copyfile(example, env_file)
    return env_file


def _ensure_web_build(root: Path, *, build: bool) -> bool:
    """Build the web UI when it is missing and Node is available."""
    index = root / "web" / "dist" / "index.html"
    if index.is_file():
        return True
    if not build:
        print("! web UI is not built; the API will start without the browser UI.")
        return False
    npm = shutil.which("npm")
    if npm is None:
        print("! web UI is not built and npm was not found; starting without the browser UI.")
        print("  Install Node.js and run `npm --prefix web install && npm --prefix web run build`.")
        return False
    print("Building the web UI for the first demo run (this can take a minute)...")
    result = subprocess.run([npm, "run", "build"], cwd=root / "web", check=False)
    if result.returncode != 0 or not index.is_file():
        print("! web build failed; the API will start without the browser UI.")
        return False
    return True


def _start_mock(root: Path, port: int) -> subprocess.Popen | None:
    """Start the bundled mock model when this checkout ships one."""
    if not (root / "mock" / "main.py").is_file():
        return None
    print(f"Starting the deterministic mock model on 127.0.0.1:{port} ...")
    process = subprocess.Popen(
        [
            sys.executable,
            "-m",
            "uvicorn",
            "mock.main:app",
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "--log-level",
            "warning",
        ],
        cwd=root,
    )
    deadline = time.monotonic() + 20
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise SystemExit("mock model exited before it became ready")
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=0.5) as response:
                if response.status == 200:
                    return process
        except OSError:
            time.sleep(0.25)
    process.terminate()
    raise SystemExit("mock model did not become ready within 20 seconds")


def _print_demo_urls(host: str, port: int) -> None:
    lan = _lan_address()
    print("")
    print("Bridge-Agents demo is ready:")
    print(f"  Customer UI:   http://localhost:{port}/")
    print(f"  Support desk:  http://localhost:{port}/admin")
    print(f"  API health:    http://localhost:{port}/health")
    if host == "0.0.0.0" and lan not in ("127.0.0.1", ""):
        print(f"  From your LAN: http://{lan}:{port}/")
    print("  Demo login is enabled (no password); press Ctrl+C to stop.")
    print("")


def _command_demo(args: argparse.Namespace) -> int:
    root = _repo_root()
    if root is None:
        print("`bridge-agents demo` must run from the Bridge-Agents source checkout.")
        print("Install the app inside a checkout, or use `docker compose up --build`.")
        return 2
    created = _ensure_env_file(root)
    if created is not None:
        print(f"Created {created} from .env.example for the demo.")
    os.environ.update(_demo_environment(root, args.mock_port))
    _ensure_web_build(root, build=not args.no_build)
    mock = _start_mock(root, args.mock_port)
    _print_demo_urls(args.host, args.port)
    try:
        import uvicorn

        uvicorn.run("app.main:app", host=args.host, port=args.port, log_level="info")
    except KeyboardInterrupt:
        pass
    finally:
        if mock is not None:
            mock.terminate()
            try:
                mock.wait(timeout=10)
            except subprocess.TimeoutExpired:
                mock.kill()
    return 0


def _command_serve(args: argparse.Namespace) -> int:
    settings = _load_settings(args.config)
    host = args.host or settings.host
    port = args.port or settings.port
    import uvicorn

    uvicorn.run("app.main:app", host=host, port=port, reload=args.reload)
    return 0


def _command_init(args: argparse.Namespace) -> int:
    config_path = Path(args.config).expanduser()
    env_path = Path(args.env_file).expanduser()
    existing = [str(path) for path in (config_path, env_path) if path.exists()]
    if existing and not args.force:
        print("Refusing to overwrite existing files (use --force):")
        for path in existing:
            print(f"  {path}")
        return 1

    environment = "production" if args.production else "development"
    allowed_hosts = "support.example.com" if args.production else "*"
    config_text = TOML_TEMPLATE.format(
        app_env=environment,
        allowed_hosts=allowed_hosts,
        allow_dev_login="false" if args.production else "true",
    )
    config_path.parent.mkdir(parents=True, exist_ok=True)
    config_path.write_text(config_text, encoding="utf-8")

    env_text = ENV_TEMPLATE.format(jwt_secret=secrets.token_urlsafe(48))
    env_path.parent.mkdir(parents=True, exist_ok=True)
    previous_mode = env_path.stat().st_mode if env_path.exists() else None
    env_path.write_text(env_text, encoding="utf-8")
    try:
        env_path.chmod(0o600)
    except OSError:  # pragma: no cover - Windows ACLs may ignore POSIX modes
        pass
    _ = previous_mode

    print("Configuration written:")
    print(f"  {config_path}  (non-secret settings)")
    print(f"  {env_path}  (secrets)")
    print("")
    print("Next steps:")
    print("  1. edit .env and set the model/moderation API keys")
    print(f"  2. bridge-agents init-db --config {config_path}")
    print(f"  3. bridge-agents config check --config {config_path}")
    print(f"  4. bridge-agents serve --config {config_path}")
    print("  5. deploy the web UI release artifact behind nginx; see deploy/README.md")
    return 0


def _command_config_check(args: argparse.Namespace) -> int:
    try:
        settings = _load_settings(args.config)
    except Exception as exc:  # configuration errors should be friendly, not tracebacks
        print(f"error: could not load configuration: {exc}")
        return 1
    print("Effective configuration")
    print(f"  app_env:        {settings.app_env}")
    print(f"  database:       {settings.database_url}")
    print(f"  auth verifier:  {settings.auth_verifier}")
    print(f"  dev login:      {settings.allow_dev_login}")
    print(f"  llm provider:   {settings.llm_provider} ({settings.openai_model})")
    print(f"  web UI dir:     {settings.web_dist_dir or '(disabled)'}")
    issues = _settings_issues(settings)
    if not issues:
        print("Configuration looks good.")
        return 0
    errors = [issue for issue in issues if issue[0] == "error"]
    for level, message in issues:
        print(f"  {level}: {message}")
    print(f"{len(errors)} error(s), {len(issues) - len(errors)} warning(s).")
    return 1 if errors else 0


def _command_init_db(args: argparse.Namespace | None = None) -> int:
    import asyncio

    config_path = getattr(args, "config", None) if args is not None else None
    if config_path:
        os.environ["BRIDGE_CONFIG"] = str(Path(config_path).expanduser().resolve())
    from app.models.database import dispose_engine, init_db

    async def run() -> None:
        await init_db()
        await dispose_engine()

    asyncio.run(run())
    print("Database schema is ready.")
    return 0


def _command_version() -> int:
    versions: dict[str, str] = {}
    for package in ("bridge-agents-server", "bridge-agents"):
        try:
            versions[package] = distribution_version(package)
        except PackageNotFoundError:
            versions[package] = "not installed"
    print(f"Python {sys.version.split()[0]}")
    for package, version in versions.items():
        print(f"{package} {version}")
    return 0


def _command_doctor() -> int:
    root = _repo_root()
    print("Bridge-Agents doctor")
    print(f"  Python:        {sys.version.split()[0]}")
    print(f"  Checkout:      {root or 'not detected'}")
    if root is None:
        return 0
    env_file = root / ".env"
    env_state = "present" if env_file.is_file() else "missing (init/demo create it)"
    print(f"  .env:          {env_state}")
    web_index = root / "web" / "dist" / "index.html"
    print(f"  Web UI build:  {'present' if web_index.is_file() else 'missing'}")
    mock = root / "mock" / "main.py"
    print(f"  Mock model:    {'present' if mock.is_file() else 'missing'}")
    print(f"  npm:           {shutil.which('npm') or 'not found'}")
    for port in (8000, 8001):
        busy = _port_in_use(port)
        print(f"  Port {port}:      {'in use' if busy else 'free'}")
    return 0


def _port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.settimeout(0.2)
        return probe.connect_ex(("127.0.0.1", port)) == 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="bridge-agents",
        description="Bridge-Agents server: deployment, demo and maintenance commands.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    serve = subparsers.add_parser("serve", help="serve the API and built web UI")
    serve.add_argument("--config", default=None, help="path to bridge-agents.toml")
    serve.add_argument("--host", default=None)
    serve.add_argument("--port", type=int, default=None)
    serve.add_argument("--reload", action="store_true", help="reload on Python changes")
    serve.set_defaults(handler=_command_serve)

    init = subparsers.add_parser("init", help="write a starter configuration and secrets")
    init.add_argument("--config", default=DEFAULT_CONFIG_FILE)
    init.add_argument("--env-file", default=DEFAULT_ENV_FILE)
    init.add_argument("--force", action="store_true", help="overwrite existing files")
    init.add_argument("--production", action="store_true", help="production-safe defaults")
    init.set_defaults(handler=_command_init)

    config = subparsers.add_parser("config", help="configuration helpers")
    config_subparsers = config.add_subparsers(dest="config_command", required=True)
    check = config_subparsers.add_parser("check", help="validate the effective configuration")
    check.add_argument("--config", default=None, help="path to bridge-agents.toml")
    check.set_defaults(handler=_command_config_check)

    init_db = subparsers.add_parser("init-db", help="create the database schema")
    init_db.add_argument("--config", default=None, help="path to bridge-agents.toml")
    init_db.set_defaults(handler=_command_init_db)

    demo = subparsers.add_parser("demo", help="one-command local demo (mock model + API + UI)")
    demo.add_argument("--host", default=DEFAULT_HOST)
    demo.add_argument("--port", type=int, default=DEFAULT_PORT)
    demo.add_argument("--mock-port", type=int, default=DEFAULT_MOCK_PORT)
    demo.add_argument("--no-build", action="store_true", help="never build the web UI")
    demo.set_defaults(handler=_command_demo)

    version = subparsers.add_parser("version", help="print package versions")
    version.set_defaults(handler=lambda _args: _command_version())

    doctor = subparsers.add_parser("doctor", help="check the local demo prerequisites")
    doctor.set_defaults(handler=lambda _args: _command_doctor())
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    handler = args.handler
    return int(handler(args))


if __name__ == "__main__":  # pragma: no cover - console-script fallback
    raise SystemExit(main())
